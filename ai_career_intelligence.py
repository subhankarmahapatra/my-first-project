def tfidf_recommendations(profile, top_n=8):
    query = " ".join(profile["skills"] + profile.get("interests", []))
    query_vector = tfidf.transform([query])
    scores = cosine_similarity(query_vector, career_matrix).ravel()
    result = career_df[["role","category","description"]].copy()
    result["Similarity_Percent"] = (scores*100).round(1)
    return result.sort_values("Similarity_Percent",ascending=False).head(top_n)

