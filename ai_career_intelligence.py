"""## 5. Career recommendation engine — explainable skill matching"""

def recommend_careers(profile, top_n=8):
    user_skills = set(normalize_skill_list(profile["skills"]))
    user_interests = set(normalize_skill_list(profile.get("interests", [])))
    rows = []
    for role in CAREER_ROLES:
        required = set(role["skills"])
        matched = sorted(user_skills & required)
        missing = sorted(required - user_skills)
        coverage = len(matched) / max(1, len(required))
        interest_match = len(user_interests & set(role["interests"])) / max(1, len(set(role["interests"])))
        score = 0.80 * coverage + 0.20 * interest_match
        rows.append({
            "Career":role["role"], "Category":role["category"],
            "Match_Score":round(score*100,1), "Skill_Coverage":round(coverage*100,1),
            "Matched_Skills":", ".join(matched) or "None yet",
            "Missing_Skills":", ".join(missing),
            "Indicative_Range_LPA":f'{role["salary_min_lpa"]:.1f}–{role["salary_max_lpa"]:.1f}'
        })
    return pd.DataFrame(rows).sort_values("Match_Score",ascending=False).head(top_n).reset_index(drop=True)

