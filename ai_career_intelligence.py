"""## 7. Skill-gap analysis and personalized learning roadmap"""

def skill_gap_report(profile, career_name):
    role = next((r for r in CAREER_ROLES if r["role"] == career_name), None)
    if role is None:
        raise ValueError("Career not found in the knowledge base.")
    current, required = set(normalize_skill_list(profile["skills"])), set(role["skills"])
    matched, missing = sorted(current & required), sorted(required - current)
    return {
        "career":career_name, "matched_skills":matched, "missing_skills":missing,
        "coverage_percent":round(100*len(matched)/max(1,len(required)),1),
        "roadmap":role["learning"]
    }

