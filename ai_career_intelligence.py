"""## 9. Job matching and ranking"""

def recommend_jobs(profile, top_n=10, location_preference=None):
    skills = set(normalize_skill_list(profile["skills"]))
    rows = []
    for _, job in jobs_df.iterrows():
        required = set(job["required_skills"])
        matched, missing = sorted(skills & required), sorted(required - skills)
        coverage = len(matched)/max(1,len(required))
        location_bonus = 0.05 if location_preference and job["location"] == location_preference else 0
        rows.append({
            "Job_ID":job["job_id"],"Title":job["title"],"Company":job["company"],
            "Location":job["location"],"Experience_Required":job["experience_years"],
            "Match_Percent":round(min(1,coverage+location_bonus)*100,1),
            "Matched_Skills":", ".join(matched),"Missing_Skills":", ".join(missing),
            "Synthetic_Salary_LPA":job["salary_lpa"]
        })
    result = pd.DataFrame(rows)
    result = result[result["Experience_Required"] <= profile.get("experience_years",0)+2]
    return result.sort_values(["Match_Percent","Synthetic_Salary_LPA"],ascending=False).head(top_n)

